def knight_frames(standing_sprite_name: str, palette: dict[str, Colour],
                  frame_rows: dict[str, tuple[str, ...]]) -> tuple[SpriteDrawing, ...]:
    """The knight's animation frames in that palette, each named after his standing sprite and the frame."""
    return tuple(SpriteDrawing(f"{standing_sprite_name}_{frame}", palette, rows) for frame, rows in frame_rows.items())


